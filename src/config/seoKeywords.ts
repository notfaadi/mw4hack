/** Dedupe while preserving order. */
export function uniqueKeywords(list: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const term of list) {
    const key = term.trim().toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(term.trim());
  }
  return out;
}

export function keywordsForPath(pathname: string): string[] {
  let path = pathname || '/';
  if (!path.startsWith('/')) path = `/${path}`;
  if (path !== '/' && !path.endsWith('/')) path = `${path}/`;

  const extra = PAGE_KEYWORD_OVERRIDES[path] ?? [];
  return uniqueKeywords([...extra, ...GLOBAL_SEO_KEYWORDS]);
}

/** Meta keywords tag: comma-separated, capped to avoid oversized HTML. */
export function formatMetaKeywords(keywords: readonly string[], maxLength = 4000): string {
  const parts: string[] = [];
  let len = 0;
  for (const term of keywords) {
    const piece = term.includes(',') ? `"${term}"` : term;
    const add = parts.length ? `, ${piece}` : piece;
    if (len + add.length > maxLength) break;
    parts.push(piece);
    len += add.length;
  }
  return parts.join(', ');
}

